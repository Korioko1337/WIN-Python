"""
Einführung in die Programmierung
Wertzuweisung von Variablen

Belegung einer Variablen mit einem Wert muss spätestens vor der ersten
Verwendung der Variablen erfolgt sein

Wertzuweisung einer Variablen erfolgt durch den Zuweisungsoperator =
"""

# Wert 5 der Variablen a zuweisen:
a = 5

# Wert 5 den Variablen a, b, c und d zuweisen:
a = b = c = d = 5

# a den Wert 3 und b den Wert 4 zuweisen:
a = 3
b = 4
a, b = 3, 4

# Variablenwerte vertauschen:
a = 5
b = 10
a, b = b, a