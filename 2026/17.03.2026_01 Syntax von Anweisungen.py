"""
Einführung in die Programmierung
Anweisungen

Anweisungen (Statements) beschreiben vom Programmierer erstellte Befehle zur
Lösung einer Aufgabe.

Ein Programm besteht aus einer Folge von Anweisungen, die in einer bestimmten
Reihenfolge ausgeführt werden.

Syntax von Anweisungen in Python:
"""

# Standard: jede Anweisung in eigener Zeile
print("Hallo Welt")
print("test")
print("1234")

# Mehrere Anweisungen in einer Zeile: Trennung der Anweisungen durch Semikolon (;)
print("Hallo Welt"); print("test"); print("1234")

# Anweisungen über mehrere Zeilen
# Implizit durch offene Klammern in der Zeile
print(1+2+3+4+5
      +6+7+8)

# Explizit durch Backslash \ am Ende der Zeile
print(1+2+3+4+5+\
      6+7+8)
